// 直连上屏裁剪规整 + 等比视口（graphics/nvn/gfx/nvn/nvn_present_fit.h，nvn_mtl.m present_now / present_blit 用的同一份）。
// 10-28 斯普拉遁3 直连满屏：游戏裁剪 0,0 2346x1080、交换链贴图还是 1920x1080，旧版判越界整帧丢掉、报红 8 次。
// 期望值全部手算（不跑被测实现）：
//   裁剪超出源 → 取裁剪框落在源内的部分，从裁剪起点按 16:9 修整（宽于 16:9 留高、窄于 16:9 留宽）；源够大 → 原样；非法 → -1。
//   视口：s = min(dw/cw, dh/ch)，x = floor((dw − cw·s)/2)，y = floor((dh − ch·s)/2)，w = round(cw·s)，h = round(ch·s)；与屏比例差 < 1% 铺满。
#include "../gfx/nvn/nvn_present_fit.h"
#include <stdio.h>
#include <string.h>

static int g_bad, g_n;
#define CHECK(c, ...) do { g_n++; if (!(c)) { g_bad++; printf("✗ "); printf(__VA_ARGS__); printf("\n"); } } while (0)

static void crop_case(const char *name, int x, int y, int w, int h, int sw, int sh, int want_rc, int ex, int ey, int ew, int eh) {
    int in[4] = {x, y, w, h}, out[4] = {-7, -7, -7, -7};
    int rc = pf_crop_fit(in, (uint64_t)sw, (uint64_t)sh, out);
    CHECK(rc == want_rc && out[0] == ex && out[1] == ey && out[2] == ew && out[3] == eh,
          "%s：裁剪 %d,%d %dx%d / 源 %dx%d 期望 返回 %d、%d,%d %dx%d 实得 返回 %d、%d,%d %dx%d",
          name, x, y, w, h, sw, sh, want_rc, ex, ey, ew, eh, rc, out[0], out[1], out[2], out[3]);
    if (rc == 1) CHECK((uint64_t)out[0] + out[2] <= (uint64_t)sw && (uint64_t)out[1] + out[3] <= (uint64_t)sh, "%s：规整后仍越界", name);
}
static void vp_case(const char *name, double dw, double dh, double cw, double ch, double ex, double ey, double ew, double eh) {
    pf_vp v = pf_viewport(dw, dh, cw, ch);
    CHECK(v.x == ex && v.y == ey && v.w == ew && v.h == eh, "%s：%gx%g 放进 %gx%g 期望 %g,%g %gx%g 实得 %g,%g %gx%g",
          name, cw, ch, dw, dh, ex, ey, ew, eh, v.x, v.y, v.w, v.h);
    CHECK(v.x >= 0 && v.y >= 0 && v.x + v.w <= dw && v.y + v.h <= dh, "%s：视口越出画布", name);
}

int main(void) {
    // ① 本局现场：2346x1080 裁剪、源 1920x1080 → 退回整张源（16:9），放进 2346x1080 屏：s = min(1.221875, 1) = 1，宽 1920、左右各 (2346−1920)/2 = 213 黑边，不拉伸
    crop_case("源窄于裁剪框（喷3 开局）", 0, 0, 2346, 1080, 1920, 1080, 1, 0, 0, 1920, 1080);
    vp_case("退回后上屏", 2346, 1080, 1920, 1080, 213, 0, 1920, 1080);
    // ② 源够宽（游戏随后改 1564x720 / 交换链换成 2346 宽）→ 裁剪原样；1564/720 = 2346/1080 = 2.1722，铺满
    crop_case("源够宽、裁剪在内", 0, 0, 1564, 720, 1920, 1080, 0, 0, 0, 1564, 720);
    vp_case("满屏裁剪上屏", 2346, 1080, 1564, 720, 0, 0, 2346, 1080);
    crop_case("源与裁剪同宽（交换链已放宽）", 0, 0, 2346, 1080, 2346, 1080, 0, 0, 0, 2346, 1080);
    crop_case("裁剪正好等于源", 0, 0, 1920, 1080, 1920, 1080, 0, 0, 0, 1920, 1080);
    // ③ 只高超出：1920x1200 / 源 1920x1080 → 1920x1080
    crop_case("只高超出", 0, 0, 1920, 1200, 1920, 1080, 1, 0, 0, 1920, 1080);
    // ④ 落在源内的部分不是 16:9：2346x1200 / 源 1920x1200 → 1920x1200（16:10，窄于 16:9）留宽：高 = 1920·9/16 = 1080
    crop_case("交集 16:10 修成 16:9", 0, 0, 2346, 1200, 1920, 1200, 1, 0, 0, 1920, 1080);
    // ⑤ 带起点：100,0 2346x1080 / 源 1920x1080 → 交集 1820x1080（窄于 16:9）：高 = 1820·9/16 = 1023.75 → 1023
    crop_case("带起点超出", 100, 0, 2346, 1080, 1920, 1080, 1, 100, 0, 1820, 1023);
    // ⑥ 交集宽于 16:9：0,0 3000x500 / 源 1920x1080 → 1920x500：宽 = 500·16/9 = 888.9 → 888
    crop_case("交集宽于 16:9 留高", 0, 0, 3000, 500, 1920, 1080, 1, 0, 0, 888, 500);
    vp_case("888x500 放进 2346x1080", 2346, 1080, 888, 500, 213, 0, 1918, 1080);   // s = min(2.6419, 2.16) = 2.16 → 宽 round(1918.08) = 1918、x = floor(213.96) = 213
    // ⑦ 没有裁剪（0,0,0,0）→ 原样（输出全 0，调用方按整张）；非法照旧 −1
    crop_case("没有裁剪", 0, 0, 0, 0, 1920, 1080, 0, 0, 0, 0, 0);
    crop_case("负起点", -1, 0, 100, 100, 1920, 1080, -1, -1, 0, 100, 100);
    crop_case("零宽", 0, 0, 0, 5, 1920, 1080, -1, 0, 0, 0, 5);
    crop_case("起点在源外", 1920, 0, 100, 100, 1920, 1080, -1, 1920, 0, 100, 100);
    { int out[4] = {9, 9, 9, 9}; CHECK(pf_crop_fit(NULL, 1920, 1080, out) == 0 && !out[0] && !out[1] && !out[2] && !out[3], "空指针裁剪：期望 返回 0、全 0"); }
    // ⑧ 视口：16:9 放进 4:3 屏 → 上下黑边：s = min(1024/1920, 768/1080) = 0.5333，高 576、y = floor(96) = 96
    vp_case("16:9 放进 4:3", 1024, 768, 1920, 1080, 0, 96, 1024, 576);
    vp_case("比例差 0.17% 铺满", 2868, 1320, 1952, 900, 0, 0, 2868, 1320);
    // 出图层在根视图里的摆放（host_adapt.m layout_layer，按点算，画面一侧给比例 a 与 1）：iPhone 根视图 956x440 点（屏幕 2868x1320 像素 ÷ 3）
    //   宽屏开：出图比例 2346 / 1080 = 2.17222，视图 956 / 440 = 2.17273，差 0.023% → 铺满 0,0 956x440（旧写法宽 440·2.17222 = 955.78、右侧露 0.22 点）
    vp_case("出图层：宽屏比例差 0.023% 铺满视图", 956, 440, 2346.0 / 1080, 1, 0, 0, 956, 440);
    //   宽屏关：16:9 → s = min(956 / 1.77778, 440 / 1) = 440，宽 round(782.22) = 782、x = floor((956 − 782.22) / 2) = floor(86.89) = 86，高 440
    vp_case("出图层：16:9 放进 956x440 照旧居中留黑", 956, 440, 16.0 / 9, 1, 86, 0, 782, 440);
    // 出图层比例（host_adapt.m out_aspect → pf_out_aspect，11-03 Duo 智慧的再现 v4）。期望手算：宽屏 2346×1080 → 2346 / 1080 = 2.172222；
    //   Duo 内屏 1920×1350（游戏自出加高图或第三层加高）→ 1920 / 1350 = 1.422222（旧式 屏宽 ÷ 1080 得 1.777778，16:9 层、上下大黑）；没放宽 → 16:9
    CHECK(pf_out_aspect(1, 2346, 1080) == 2346.0 / 1080.0, "出图层比例：宽屏 2346×1080 期望 2.172222 实得 %f", pf_out_aspect(1, 2346, 1080));
    CHECK(pf_out_aspect(1, 1920, 1350) == 1920.0 / 1350.0, "出图层比例：Duo 1920×1350 期望 1.422222 实得 %f", pf_out_aspect(1, 1920, 1350));
    CHECK(pf_out_aspect(0, 2346, 1080) == 16.0 / 9.0, "出图层比例：没放宽 期望 16:9 实得 %f", pf_out_aspect(0, 2346, 1080));
    //   Duo 视图 951x669 点（2853x2007 像素 ÷ 3）放 1.422222 的层：951 / 669 = 1.421525，差 0.05% → 铺满 0,0 951x669
    vp_case("出图层：Duo 加高比例铺满视图", 951, 669, pf_out_aspect(1, 1920, 1350), 1, 0, 0, 951, 669);
    // 外接显示器（ios/extdisplay.m：出图层挪到外接屏窗口的视图，同一条 pf_viewport）。期望手算：
    //   16:9 的出图放 1920x1080 显示器：比例相同 → 铺满 0,0 1920x1080
    vp_case("外接屏：16:9 铺满 1920x1080", 1920, 1080, 16.0 / 9, 1, 0, 0, 1920, 1080);
    //   局中接上、游戏比例换不了（手机宽图 2346 / 1080）：s = min(1920 / 2.172222, 1080) = 883.89，宽 1920、高 round(883.89) = 884，y = floor((1080 − 883.89) / 2) = 98，上下留黑
    vp_case("外接屏：手机宽图放 1920x1080 上下留黑", 1920, 1080, 2346.0 / 1080, 1, 0, 98, 1920, 884);
    //   16:10 显示器 1920x1200 放 16:9：s = min(1080, 1200) = 1080，宽 1920、高 1080，y = (1200 − 1080) / 2 = 60
    vp_case("外接屏：16:9 放 16:10 显示器上下留黑", 1920, 1200, 16.0 / 9, 1, 0, 60, 1920, 1080);
    //   带鱼屏 3440x1440 放 16:9：s = min(1935, 1440) = 1440，宽 2560、高 1440，x = (3440 − 2560) / 2 = 440
    vp_case("外接屏：16:9 放 3440x1440 左右留黑", 3440, 1440, 16.0 / 9, 1, 440, 0, 2560, 1440);
    // 出图层重摆要不要等回前台（host_adapt.m s2a_direct_relayout → pf_relayout_wait）。期望按语义手写：
    //   没有外接屏时与改前相同：App 在后台就等、在前台不等（moved 恒 0）
    CHECK(pf_relayout_wait(0, 1, 0, 0) == 1, "重摆：根视图、App 后台 期望 等");
    CHECK(pf_relayout_wait(0, 1, 0, 1) == 1, "重摆：根视图、App 后台、没挪层（多任务快照）期望 等");
    CHECK(pf_relayout_wait(0, 0, 0, 1) == 0, "重摆：根视图、App 前台 期望 不等");
    //   11-10 iPhone 18 Pro 局中拔显示器实测：断开回调里 App 状态 2（后台）、根视图所在场景状态 0（前台活跃）、层刚挪回 → 当场重摆
    CHECK(pf_relayout_wait(0, 1, 1, 1) == 0, "重摆：层刚挪回根视图、根视图场景在前台 期望 不等（否则层留着外接屏尺寸）");
    //   后台期间断开（根视图场景也在后台）→ 等，回前台补
    CHECK(pf_relayout_wait(0, 1, 1, 0) == 1, "重摆：层刚挪回根视图、根视图场景在后台 期望 等");
    //   层在外接屏窗口的视图上：不受手机进后台影响
    CHECK(pf_relayout_wait(1, 1, 1, 0) == 0 && pf_relayout_wait(1, 1, 0, 0) == 0, "重摆：层在外接屏视图 期望 不等");
    printf("%s t_present_fit：直连上屏裁剪规整 + 等比视口 %d 项 → %s\n", g_bad ? "✗" : "✓", g_n, g_bad ? "有不符合项" : "全过");
    return g_bad != 0;
}
